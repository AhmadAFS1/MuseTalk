# Values of keys matching this are never printed.
MT_ENV_SECRET_RE='(^|_)(KEY|SECRET|TOKEN|PASS|PASSWORD|PASSWD|CREDENTIAL|CREDENTIALS|AUTH|PRIVATE)(_|$)'

