#!/usr/bin/env bash
# Shared env layering helpers for the MuseTalk launch chain (startup rework 2026-09-28).
#
# Sourced by scripts/run_musetalk_server.sh, scripts/run_webrtc_relay_api_server.sh,
# scripts/vast_server_ctl.sh and scripts/vast_onstart.sh. See docs/STARTUP.md.
#
# Effective value of any knob, highest wins:
#   1. the caller's environment (explicit export, Vast template env, TURN env file sourced by ctl)
#   2. operator overrides files: MUSETALK_ENV_OVERRIDES_FILE (colon-separated list; default
#      <repo>/.runtime/musetalk_overrides.env; missing files are skipped), earlier files win
#   3. <repo>/.runtime/musetalk_resolved.env, regenerated by scripts/musetalk_host_profile.py
#   4. code defaults
#
# Env files are PARSED, never sourced or eval'd: `KEY=VALUE` / `export KEY=VALUE` lines,
# blank lines and `#` comments ignored, values may be 'single-quoted' (with the '\'' idiom),
# "double-quoted" (no expansion) or bare (an inline ` # comment` after whitespace is allowed).
# `$`, backticks and shell metacharacters outside single quotes are rejected, so a file can
# never run code. A key is exported only while it is still UNSET ([[ -z "${!key+x}" ]]).

if [[ -n "${MT_ENV_LAYERS_LOADED:-}" ]]; then
  return 0
fi
MT_ENV_LAYERS_LOADED=1

declare -gA MT_ENV_SOURCE=()        # key -> caller | overrides:<file> | resolved:<file> | launcher:<why>
declare -ga MT_ENV_FILES_USED=()    # overrides files that existed and were read
declare -ga MT_ENV_OVERRIDES_FILES=()
declare -ga MT_ENV_WARNINGS=()
MT_ENV_LOG_PREFIX="${MT_ENV_LOG_PREFIX:-musetalk_env}"
MT_ENV_PARSED=""
MT_ENV_ERROR=""
MT_ENV_KEY=""
MT_ENV_VALUE=""
MT_ENV_LAST_LOADED=0
MT_ENV_LAST_KEPT=0
MT_ENV_LAST_INVALID=0
MT_ENV_PEEK_SOURCE=""
MT_ENV_PEEK_VALUE=""
MT_ENV_RECIPE="fast"
MT_ENV_RECIPE_SOURCE="default"

# Keys an env file may never set (shell/loader behaviour, not MuseTalk levers).
