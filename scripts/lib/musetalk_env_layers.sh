mt_env_log() {
  printf '[%s] %s\n' "$MT_ENV_LOG_PREFIX" "$*" >&2
}

mt_env_warn() {
  MT_ENV_WARNINGS+=("$*")
  printf '[%s] WARNING: %s\n' "$MT_ENV_LOG_PREFIX" "$*" >&2
}

mt_env_is_true() {
  case "${1:-}" in
    1|true|TRUE|True|yes|YES|Yes|on|ON|On)
      return 0
      ;;
  esac
  return 1
}

mt_env_lower() {
  printf '%s' "${1,,}"
}

mt_env_is_secret_key() {
  [[ "${1^^}" =~ $MT_ENV_SECRET_RE ]]
}

# Single-quote a value for a shell-sourceable line.
mt_env_quote() {
  local _mt_v="$1"
  printf "'%s'" "${_mt_v//\'/\'\\\'\'}"
}

# Value for logs/print-env: secrets are redacted.
mt_env_display() {
  local _mt_key="$1" _mt_value="$2"
  if mt_env_is_secret_key "$_mt_key"; then
    if [[ -n "$_mt_value" ]]; then
      printf '<redacted>'
    else
      printf "''"
    fi
    return 0
  fi
  mt_env_quote "$_mt_value"
}

# mt_env_parse_value RAW -> MT_ENV_PARSED (return 1 and MT_ENV_ERROR on a syntax error).
mt_env_parse_value() {
  local _mt_raw="$1" _mt_out="" _mt_c _mt_rest _mt_seg _mt_next _mt_closed
  local -i _mt_i=0 _mt_n
  MT_ENV_PARSED=""
  MT_ENV_ERROR=""
  _mt_raw="${_mt_raw%$'\r'}"
  _mt_raw="${_mt_raw%"${_mt_raw##*[![:space:]]}"}"
  _mt_n=${#_mt_raw}
  while (( _mt_i < _mt_n )); do
    _mt_c="${_mt_raw:_mt_i:1}"
    case "$_mt_c" in
      "'")
        _mt_rest="${_mt_raw:_mt_i+1}"
        if [[ "$_mt_rest" != *"'"* ]]; then
          MT_ENV_ERROR="unterminated single quote"
          return 1
        fi
        _mt_seg="${_mt_rest%%\'*}"
        _mt_out+="$_mt_seg"
        _mt_i=$(( _mt_i + ${#_mt_seg} + 2 ))
        ;;
      '"')
        _mt_i=$(( _mt_i + 1 ))
        _mt_closed=0
        while (( _mt_i < _mt_n )); do
          _mt_c="${_mt_raw:_mt_i:1}"
          if [[ "$_mt_c" == '"' ]]; then
            _mt_closed=1
            _mt_i=$(( _mt_i + 1 ))
            break
          elif [[ "$_mt_c" == '\' ]]; then
            _mt_next="${_mt_raw:_mt_i+1:1}"
            case "$_mt_next" in
              '"'|'\'|'$'|'`')
                _mt_out+="$_mt_next"
                _mt_i=$(( _mt_i + 2 ))
                ;;
              *)
                _mt_out+="$_mt_c"
                _mt_i=$(( _mt_i + 1 ))
                ;;
            esac
          elif [[ "$_mt_c" == '$' || "$_mt_c" == '`' ]]; then
            MT_ENV_ERROR='expansion ($ or backtick) is not supported; single-quote the value'
            return 1
          else
            _mt_out+="$_mt_c"
            _mt_i=$(( _mt_i + 1 ))
          fi
        done
        if (( ! _mt_closed )); then
          MT_ENV_ERROR="unterminated double quote"
          return 1
        fi
        ;;
      '\')
        if (( _mt_i + 1 >= _mt_n )); then
          MT_ENV_ERROR="trailing backslash"
          return 1
        fi
        _mt_out+="${_mt_raw:_mt_i+1:1}"
        _mt_i=$(( _mt_i + 2 ))
        ;;
      ' '|$'\t')
        _mt_rest="${_mt_raw:_mt_i}"
        _mt_rest="${_mt_rest#"${_mt_rest%%[![:space:]]*}"}"
        if [[ -z "$_mt_rest" || "$_mt_rest" == \#* ]]; then
          break
        fi
        MT_ENV_ERROR="unquoted whitespace in value; quote it"
        return 1
        ;;
      '$'|'`')
        MT_ENV_ERROR='expansion ($ or backtick) is not supported; single-quote the value'
        return 1
        ;;
      ';'|'|'|'&'|'<'|'>'|'('|')')
        MT_ENV_ERROR="unquoted shell metacharacter '$_mt_c'; quote the value"
        return 1
        ;;
      *)
        _mt_out+="$_mt_c"
        _mt_i=$(( _mt_i + 1 ))
        ;;
    esac
  done
  MT_ENV_PARSED="$_mt_out"
  return 0
}

# mt_env_parse_line LINE -> 0 assignment (MT_ENV_KEY/MT_ENV_VALUE), 1 blank/comment, 2 invalid.
mt_env_parse_line() {
  local _mt_line="${1%$'\r'}" _mt_key _mt_raw
  _mt_line="${_mt_line#"${_mt_line%%[![:space:]]*}"}"
  if [[ -z "$_mt_line" || "$_mt_line" == \#* ]]; then
    return 1
  fi
  if [[ "$_mt_line" =~ ^export[[:space:]]+ ]]; then
    _mt_line="${_mt_line#export}"
    _mt_line="${_mt_line#"${_mt_line%%[![:space:]]*}"}"
  fi
  if [[ "$_mt_line" != *=* ]]; then
    MT_ENV_ERROR="not a KEY=VALUE line"
    return 2
  fi
  _mt_key="${_mt_line%%=*}"
  _mt_raw="${_mt_line#*=}"
  if ! [[ "$_mt_key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
    MT_ENV_ERROR="invalid variable name '${_mt_key}'"
    return 2
  fi
  if [[ "$_mt_key" =~ $MT_ENV_DENY_RE ]]; then
    MT_ENV_ERROR="variable '${_mt_key}' may not be set from an env file"
    return 2
  fi
  if ! mt_env_parse_value "$_mt_raw"; then
    return 2
  fi
  MT_ENV_KEY="$_mt_key"
  MT_ENV_VALUE="$MT_ENV_PARSED"
  return 0
}

# Record every variable already exported as coming from the caller.
mt_env_record_caller() {
  local _mt_name
  while IFS= read -r _mt_name; do
    [[ -n "$_mt_name" ]] || continue
    if [[ -z "${MT_ENV_SOURCE[$_mt_name]:-}" ]]; then
      MT_ENV_SOURCE[$_mt_name]="caller"
    fi
  done < <(compgen -e)
}

# mt_env_load_file FILE LABEL: export each assignment only while the key is still unset.
mt_env_load_file() {
  local _mt_file="$1" _mt_label="${2:-$1}" _mt_line _mt_rc
  local -i _mt_lineno=0
  MT_ENV_LAST_LOADED=0
  MT_ENV_LAST_KEPT=0
  MT_ENV_LAST_INVALID=0
  if [[ ! -e "$_mt_file" ]]; then
    return 0
  fi
  if [[ ! -f "$_mt_file" || ! -r "$_mt_file" ]]; then
    mt_env_warn "cannot read env file $_mt_file; skipped"
    return 0
  fi
  while IFS= read -r _mt_line || [[ -n "$_mt_line" ]]; do
    _mt_lineno=$(( _mt_lineno + 1 ))
    _mt_rc=0
    mt_env_parse_line "$_mt_line" || _mt_rc=$?
    case "$_mt_rc" in
      0)
        if [[ -z "${!MT_ENV_KEY+x}" ]]; then
          export "$MT_ENV_KEY=$MT_ENV_VALUE"
          MT_ENV_SOURCE[$MT_ENV_KEY]="$_mt_label"
          MT_ENV_LAST_LOADED=$(( MT_ENV_LAST_LOADED + 1 ))
        else
          MT_ENV_LAST_KEPT=$(( MT_ENV_LAST_KEPT + 1 ))
        fi
        ;;
      1)
        ;;
      *)
        MT_ENV_LAST_INVALID=$(( MT_ENV_LAST_INVALID + 1 ))
        mt_env_warn "$_mt_file:$_mt_lineno ignored: $MT_ENV_ERROR"
        ;;
    esac
  done < "$_mt_file"
  return 0
}

# mt_env_file_get FILE KEY: print the FIRST value FILE assigns to KEY (what loading would export).
mt_env_file_get() {
  local _mt_file="$1" _mt_want="$2" _mt_line _mt_rc
  [[ -f "$_mt_file" && -r "$_mt_file" ]] || return 1
  while IFS= read -r _mt_line || [[ -n "$_mt_line" ]]; do
    _mt_rc=0
    mt_env_parse_line "$_mt_line" || _mt_rc=$?
    if (( _mt_rc == 0 )) && [[ "$MT_ENV_KEY" == "$_mt_want" ]]; then
      printf '%s' "$MT_ENV_VALUE"
      return 0
    fi
  done < "$_mt_file"
  return 1
}

# mt_env_file_keys FILE: print each assigned key once (file order).
mt_env_file_keys() {
  local _mt_file="$1" _mt_line _mt_rc
  local -A _mt_seen=()
  [[ -f "$_mt_file" && -r "$_mt_file" ]] || return 0
  while IFS= read -r _mt_line || [[ -n "$_mt_line" ]]; do
    _mt_rc=0
    mt_env_parse_line "$_mt_line" || _mt_rc=$?
    if (( _mt_rc == 0 )) && [[ -z "${_mt_seen[$MT_ENV_KEY]:-}" ]]; then
      _mt_seen[$MT_ENV_KEY]=1
      printf '%s\n' "$MT_ENV_KEY"
    fi
  done < "$_mt_file"
}

# mt_env_overrides_list REPO_ROOT -> MT_ENV_OVERRIDES_FILES (configured order; may not exist).
mt_env_overrides_list() {
  local _mt_repo="$1" _mt_spec _mt_item
  local _mt_default="${MUSETALK_RUNTIME_DIR:-$_mt_repo/.runtime}/musetalk_overrides.env"
  local -a _mt_items=()
  MT_ENV_OVERRIDES_FILES=()
  if [[ -n "${MUSETALK_ENV_OVERRIDES_FILE+x}" ]]; then
    _mt_spec="$MUSETALK_ENV_OVERRIDES_FILE"
  else
    _mt_spec="$_mt_default"
  fi
  IFS=':' read -r -a _mt_items <<< "$_mt_spec" || true
  for _mt_item in "${_mt_items[@]}"; do
    [[ -n "$_mt_item" ]] || continue
    if [[ "$_mt_item" != /* ]]; then
      _mt_item="$_mt_repo/$_mt_item"
    fi
    MT_ENV_OVERRIDES_FILES+=("$_mt_item")
  done
}

# mt_env_load_overrides REPO_ROOT: layer 2, earlier files win, missing files skipped.
mt_env_load_overrides() {
  local _mt_file
  mt_env_overrides_list "$1"
  MT_ENV_FILES_USED=()
  for _mt_file in "${MT_ENV_OVERRIDES_FILES[@]}"; do
    if [[ ! -e "$_mt_file" ]]; then
      continue
    fi
    mt_env_load_file "$_mt_file" "overrides:$_mt_file"
    MT_ENV_FILES_USED+=("$_mt_file")
    mt_env_log "overrides $_mt_file: exported=$MT_ENV_LAST_LOADED kept_higher_layer=$MT_ENV_LAST_KEPT invalid=$MT_ENV_LAST_INVALID"
  done
}

# mt_env_peek KEY REPO_ROOT: the value KEY will have after layer 2 (caller env, else the first
# overrides file that assigns it) WITHOUT exporting anything. Sets MT_ENV_PEEK_VALUE and
# MT_ENV_PEEK_SOURCE; returns 1 (both empty) when neither layer sets KEY. Prints nothing.
mt_env_peek() {
  local _mt_key="$1" _mt_repo="$2" _mt_file _mt_value
  MT_ENV_PEEK_VALUE=""
  MT_ENV_PEEK_SOURCE=""
  if [[ -n "${!_mt_key+x}" ]]; then
    MT_ENV_PEEK_VALUE="${!_mt_key}"
    MT_ENV_PEEK_SOURCE="${MT_ENV_SOURCE[$_mt_key]:-caller}"
    return 0
  fi
  mt_env_overrides_list "$_mt_repo"
  for _mt_file in "${MT_ENV_OVERRIDES_FILES[@]}"; do
    if _mt_value="$(mt_env_file_get "$_mt_file" "$_mt_key")"; then
      MT_ENV_PEEK_VALUE="$_mt_value"
      MT_ENV_PEEK_SOURCE="overrides:$_mt_file"
      return 0
    fi
  done
  return 1
}

# mt_env_peek_or KEY REPO_ROOT DEFAULT: print the peeked value, or DEFAULT.
mt_env_peek_or() {
  if mt_env_peek "$1" "$2"; then
    printf '%s' "$MT_ENV_PEEK_VALUE"
  else
    printf '%s' "${3:-}"
  fi
}

# mt_env_effective_recipe REPO_ROOT -> MT_ENV_RECIPE (fast default | fast300 | legacy_int8 |
# anything else, left for the caller to reject) and MT_ENV_RECIPE_SOURCE. Prints nothing.
mt_env_effective_recipe() {
  local _mt_value=""
  MT_ENV_RECIPE_SOURCE="default"
  if mt_env_peek MUSETALK_RECIPE "$1"; then
    _mt_value="$MT_ENV_PEEK_VALUE"
    MT_ENV_RECIPE_SOURCE="$MT_ENV_PEEK_SOURCE"
  fi
  _mt_value="${_mt_value,,}"
  _mt_value="${_mt_value//[[:space:]]/}"
  case "$_mt_value" in
    ""|default)
      MT_ENV_RECIPE="fast"
      ;;
    legacy|int8|legacy-int8)
      MT_ENV_RECIPE="legacy_int8"
      ;;
    *)
      MT_ENV_RECIPE="$_mt_value"
      ;;
  esac
}
